"""A07: weak session identifiers — a supplied --cookie, or an Authorization: Bearer
token supplied with --header (passive: only inspects what you gave it).

For a Bearer token that parses as a JWT (header.payload.signature, each segment valid
base64url JSON for header/payload), the header and payload are decoded and checked for
structural red flags. This never touches the signature itself — no key is needed, and
no claim about whether the signature is actually valid is made.
"""
from __future__ import annotations

import base64
import binascii
import json
import re

from ..models import Finding, Severity
from .base import Check, ScanContext, register

SESSION_LIKE = re.compile(r"sess|auth|token|jwt|sid|login", re.IGNORECASE)
MIN_LENGTH = 16


def _looks_low_entropy(value: str) -> bool:
    """Cheap, explainable heuristic: not a length/charset check substitute for real entropy,
    but catches the common weak cases — short values, all-digits, or heavily repeated runs."""
    if len(value) < MIN_LENGTH:
        return True
    if value.isdigit():
        return True
    longest_run = max(len(run) for run in re.findall(r"(.)\1*", value))
    return longest_run >= max(4, len(value) // 4)


def _b64url_json(segment: str) -> dict | None:
    """Decode one base64url JWT segment as JSON, or None if it isn't one. Never raises."""
    padded = segment + "=" * (-len(segment) % 4)
    try:
        decoded = base64.urlsafe_b64decode(padded)
        parsed = json.loads(decoded)
    except (binascii.Error, ValueError, UnicodeDecodeError):
        return None
    return parsed if isinstance(parsed, dict) else None


def decode_jwt(token: str) -> tuple[dict, dict] | None:
    """Return (header, payload) if token has JWT structure, else None. Ignores the
    signature segment entirely — this is a structural read, not a verification."""
    parts = token.split(".")
    if len(parts) != 3:
        return None
    header, payload = _b64url_json(parts[0]), _b64url_json(parts[1])
    return (header, payload) if header is not None and payload is not None else None


@register
class SessionCheck(Check):
    id = "session"
    category = "A07"
    description = "Weak-looking session cookies and bearer tokens"

    def run(self, ctx: ScanContext) -> list[Finding]:
        findings = []
        for name, value in ctx.config.cookies.items():
            if not SESSION_LIKE.search(name):
                continue
            if _looks_low_entropy(value):
                findings.append(self.finding(
                    f"Session cookie '{name}' looks weak or predictable", Severity.MEDIUM,
                    ctx.landing.url,
                    f"Cookie '{name}' is short, numeric, or has long repeated runs "
                    f"({len(value)} character(s)).",
                    "Use a long, cryptographically random session identifier "
                    "(128+ bits), generated by a trusted framework, not custom code."))

        for name, value in ctx.config.headers.items():
            if name.lower() != "authorization":
                continue
            match = re.match(r"Bearer\s+(.+)", value, re.IGNORECASE)
            if not match:
                continue
            findings.extend(self._inspect_bearer(match.group(1), ctx.landing.url))
        return findings

    def _inspect_bearer(self, token: str, url: str):
        decoded = decode_jwt(token)
        if decoded is None:
            if _looks_low_entropy(token):
                yield self.finding(
                    "Bearer token looks weak or predictable", Severity.MEDIUM, url,
                    f"Authorization token is short, numeric, or has long repeated runs "
                    f"({len(token)} character(s)).",
                    "Use a long, cryptographically random token, or a properly signed JWT.")
            return

        header, payload = decoded
        alg = str(header.get("alg", "")).lower()
        if alg in ("none", ""):
            yield self.finding(
                "JWT accepts an unsigned token ('alg': 'none')", Severity.HIGH, url,
                f"The token's header declares alg={header.get('alg')!r}, which some JWT "
                "libraries will accept with no signature check at all, letting anyone "
                "forge a token by editing the payload.",
                "Reject tokens with alg=none server-side; pin the expected algorithm "
                "(e.g. RS256/HS256) rather than trusting the token's own header.")
        if "exp" not in payload:
            yield self.finding(
                "JWT has no expiration claim", Severity.MEDIUM, url,
                "The token's payload has no 'exp' field, so it may never expire once issued.",
                "Issue tokens with a short, enforced expiration ('exp') and a refresh flow.")
